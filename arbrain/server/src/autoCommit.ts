/** Publish cron outputs on the Mini without rebasing or consuming a user's index. */
import { execFileSync } from 'child_process'
import { existsSync, readFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { join } from 'path'
import { logger } from './logger.js'
import { esEdicionCliente } from './edicion.js'

const ROOT = fileURLToPath(new URL('../../../', import.meta.url))
const PATHS = [
  '.claude/knowledge/', '.claude/memory/',
  'arbrain/server/scripts/analytics/autoresearch_levy_results.tsv',
  'arbrain/server/scripts/analytics/autoresearch_sensei_results.tsv',
  'arbrain/server/scripts/analytics/autoresearch_trinity_results.tsv',
  'negocio/saas-factory-community',
]
// Host that publishes cron outputs: the Arbrain server (Mini until 24 sep 2026, Studio since).
// Keep in sync with SERVER_SLUG in arbrain/server/scripts/server_host.py.
export const PUBLISHER_SLUG = 'studio'
const allowed = (path: string) => PATHS.some(p => p.endsWith('/') ? path.startsWith(p) : path === p)

/** Injectable root supports real Git integration tests, never shell interpolation. */
export function publishCronChanges(root: string, jobId: string): string {
  const git = (args: string[], cwd = root) => execFileSync('git', args, {
    cwd, encoding: 'utf8', timeout: 60_000, stdio: ['ignore', 'pipe', 'pipe'],
  }).trimEnd()
  const staged = () => git(['diff', '--cached', '--name-only', '-z']).split('\0').filter(Boolean)
  // Even an unrelated staged file is owned by its author. Leave the entire index alone.
  if (staged().length) return 'blocked: existing staged changes'
  if (git(['diff', '--name-only', '--diff-filter=U'])) return 'blocked: unresolved conflicts'
  const branch = git(['symbolic-ref', '--quiet', '--short', 'HEAD'])
  git(['fetch', '--quiet', 'origin', `refs/heads/${branch}:refs/remotes/origin/${branch}`])
  const upstream = `refs/remotes/origin/${branch}`
  const counts = git(['rev-list', '--left-right', '--count', `HEAD...${upstream}`]).split(/\s+/).map(Number)
  if (counts[0] && counts[1]) return 'blocked: branch diverged; no automatic rebase'
  if (counts[1]) git(['merge', '--ff-only', '--quiet', upstream])

  // NUL-delimited name lists handle spaces, newlines and shell metacharacters literally.
  // A different cron may finish while the compiler is still writing its wiki.
  // Defer wiki publication while the compiler lock is present.
  const publishable = (path: string) => allowed(path) && !(path.startsWith('.claude/knowledge/')
    && existsSync(join(root, '.claude/hooks/tmp/compile.lock')))
  const files = [...new Set([
    ...git(['diff', '--no-renames', '--name-only', '-z', 'HEAD']).split('\0'),
    ...git(['ls-files', '--others', '--exclude-standard', '-z']).split('\0'),
  ].filter(Boolean))].filter(publishable)
  if (files.includes('negocio/saas-factory-community')) {
    const sub = join(root, 'negocio/saas-factory-community')
    const head = git(['rev-parse', 'HEAD'], sub)
    git(['fetch', '--quiet', 'origin'], sub)
    // Fetchable remote history is the proof, not the existence of a local upstream.
    if (!git(['for-each-ref', `--contains=${head}`, '--format=%(refname)', 'refs/remotes/origin/'], sub)) {
      return 'blocked: submodule commit is not published on origin'
    }
  }
  if (files.length) {
    if (staged().length) return 'blocked: index changed during fetch'
    git(['add', '--', ...files])
    const actual = staged()
    if (actual.some(path => !publishable(path))) return 'blocked: index changed concurrently; preserved'
    if (actual.length) {
      // --only excludes concurrent staging outside this explicit list. No global reset on failure.
      git(['commit', '--only', '-m', `auto(${jobId}): ${actual.length} file(s) updated`,
        '-m', 'Generated by claudeclaw scheduler.', '--', ...actual])
    }
  }
  const pending = Number(git(['rev-list', '--count', `${upstream}..HEAD`]))
  if (!pending) return 'up-to-date'
  // Retry a failed push even when this cron produced no new files. Never publish manual commits.
  const messages = git(['log', '--format=%B%x00', `${upstream}..HEAD`]).split('\0').filter(s => s.trim())
  if (messages.some(m => !/^auto\([^\n]*\): /m.test(m) && !/^hipocampo: /m.test(m))) {
    return 'blocked: unpublished manual commits require their author'
  }
  git(['push', 'origin', `HEAD:refs/heads/${branch}`])
  return `published ${pending} commit(s)`
}

let publishing = false
export async function autoCommitCronChanges(jobId: string): Promise<void> {
  if (publishing) return
  publishing = true
  try {
    // Edición cliente (AUDITORIA I10): el repo de la persona es suyo; nunca se publica nada solo.
    if (esEdicionCliente()) return
    if (readFileSync(join(ROOT, '.claude/hooks/.host-slug'), 'utf8').trim() !== PUBLISHER_SLUG) return
    const result = publishCronChanges(ROOT, jobId)
    if (result.startsWith('blocked:')) logger.warn({ jobId, result }, 'auto-commit: attention required')
    else logger.info({ jobId, result }, 'auto-commit: publication checked')
  } catch (err) {
    logger.error({ jobId, err }, 'auto-commit: publication failed; files/index preserved for retry')
  } finally { publishing = false }
}
